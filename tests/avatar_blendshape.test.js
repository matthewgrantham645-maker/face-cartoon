'use strict';
const assert=require('node:assert/strict');
const {expressionFromBlendshapes}=require('../docs/avatar/blendshape-driver.js');
const {mapPose}=require('../docs/avatar/mesh-bridge.js');
const named=pairs=>pairs.map(([categoryName,score])=>({categoryName,score}));
const rest=expressionFromBlendshapes([]);
assert.equal(rest.eyeL,1);assert.equal(rest.eyeR,1);assert.equal(rest.smile,0);assert.equal(rest.brow,0);assert.equal(rest.jaw,0);
const blink=expressionFromBlendshapes(named([['eyeBlinkLeft',1],['eyeBlinkRight',0]]));
assert.equal(blink.eyeL,0);assert.equal(blink.eyeR,1);
const smile=expressionFromBlendshapes(named([['mouthSmileLeft',.8],['mouthSmileRight',.8]]));
assert(smile.smile>.7);assert(mapPose(smile).eyeSmile>=.5);assert(mapPose(smile).mouthForm<0);
const frown=expressionFromBlendshapes(named([['mouthFrownLeft',.8],['mouthFrownRight',.8]]));
assert(frown.smile<-.7);
const brows=expressionFromBlendshapes(named([['browOuterUpLeft',.9],['browOuterUpRight',.9],['browInnerUp',.4]]));
assert(brows.brow>.4);assert.equal(mapPose(brows).browAngle,0);
const oneBrow=expressionFromBlendshapes(named([['browOuterUpLeft',1]]));
assert(mapPose(oneBrow).browAngle>0);assert(mapPose({brow:.5,browL:.4,browR:-.4}).browY===.5);
assert(expressionFromBlendshapes(named([['jawOpen',.5]])).jaw>.5);
assert(expressionFromBlendshapes(named([['mouthPucker',.8]])).pucker>.7);
assert.equal(expressionFromBlendshapes(named([['eyeBlinkLeft',NaN],['tongueOut',1]])).eyeL,1);
assert(Object.values(mapPose({smile:1,pucker:1,squint:1,brow:1,browL:1,browR:-1})).every(Number.isFinite));
console.log('PASS: blendshape eyes, smile, frown, brows, jaw and pucker map into visible mesh channels.');
